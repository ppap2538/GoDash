"""Real roundabouts (OSM junction=roundabout rings) -> src/shared/Config/Maps/KhonKaenData/Roundabouts.luau

  python -I -X utf8 tools/osm_roundabouts.py

Each ring becomes { x, z, r, cls, name } in studs (same projection as tools/osm_to_map.py: origin
LAT0/LON0, 1 stud = 0.28 m). r = the mean distance of the ring's nodes from its centre (the middle of
the road). World/RoadMarks builds the centre island only where the road graph really has the ring.
Map data (c) OpenStreetMap contributors, ODbL.
"""
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "osm_tambon.json")
OUT = os.path.join(ROOT, "src", "shared", "Config", "Maps", "KhonKaenData", "Roundabouts.luau")
STUD = 0.28
LAT0, LON0 = 16.4225, 102.8310  # never change (see osm_to_map.py)
MX = 111320 * math.cos(math.radians(LAT0))
MZ = 110574
KEEP = {"primary", "secondary", "tertiary", "unclassified", "residential", "service", "living_street"}


def xy(lat, lon):
    return ((lon - LON0) * MX, -(lat - LAT0) * MZ)


def main():
    data = json.load(open(RAW, encoding="utf-8"))
    out = []
    for e in data["elements"]:
        t = e.get("tags", {})
        if e.get("type") != "way" or t.get("junction") not in ("roundabout", "circular"):
            continue
        if t.get("highway") not in KEEP or "geometry" not in e:
            continue
        pts = [xy(g["lat"], g["lon"]) for g in e["geometry"]]
        if len(pts) < 5:
            continue
        cx = sum(p[0] for p in pts) / len(pts)
        cz = sum(p[1] for p in pts) / len(pts)
        r = sum(math.dist(p, (cx, cz)) for p in pts) / len(pts)
        if r < 6:  # a mini roundabout painted on the road: nothing to build
            continue
        out.append((cx / STUD, cz / STUD, r / STUD, t.get("highway"), t.get("name", "")))
    out.sort(key=lambda o: -o[2])
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/osm_roundabouts.py from OpenStreetMap data (c) OpenStreetMap contributors, ODbL.\n")
        f.write("-- { x, z, r (ring radius, studs), cls (OSM highway class) }\n")
        f.write("return {\n")
        for x, z, r, cls, name in out:
            f.write('\t{ x = %d, z = %d, r = %.1f, cls = "%s" },\n' % (round(x), round(z), r, cls))
        f.write("}\n")
    print("roundabouts: %d" % len(out))
    for x, z, r, cls, name in out:
        print("  %7d %7d  r=%6.1f studs (%5.1f m)  %s %s" % (x, z, r, r * STUD, cls, name))


if __name__ == "__main__":
    main()
