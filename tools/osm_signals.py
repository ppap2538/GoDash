"""Real traffic signals (OSM highway=traffic_signals) -> src/shared/Config/Maps/KhonKaenData/Signals.luau

  python -I -X utf8 tools/osm_signals.py            fetch from Overpass into data/osm_signals.json, then write
  python -I -X utf8 tools/osm_signals.py --offline  only rewrite the .luau from data/osm_signals.json

Each signal node becomes { x, z } in studs (same projection as tools/osm_to_map.py: origin LAT0/LON0, 1 stud = 0.28 m).
shared/Traffic only lights a junction when one of these stands at it (2026-11-18, owner: junctions with many
overlapping lights were confusing; the old rule lit 312 junctions, most of them not signalled in real life).
Pedestrian-crossing signals (highway=crossing) are not included.
Map data (c) OpenStreetMap contributors, ODbL.
"""
import json
import math
import os
import sys
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "osm_signals.json")
OUT = os.path.join(ROOT, "src", "shared", "Config", "Maps", "KhonKaenData", "Signals.luau")
STUD = 0.28
LAT0, LON0 = 16.4225, 102.8310  # never change (see osm_to_map.py)
MX = 111320 * math.cos(math.radians(LAT0))
MZ = 110574
BBOX = "16.3975,102.8020,16.4825,102.8785"  # same box as tools/osm_fetch.mjs
SERVERS = [
    "https://overpass-api.de/api/interpreter",
    "https://overpass.kumi.systems/api/interpreter",
    "https://overpass.openstreetmap.fr/api/interpreter",
]


def xy(lat, lon):
    return ((lon - LON0) * MX, -(lat - LAT0) * MZ)


def fetch():
    q = '[out:json][timeout:90];node["highway"="traffic_signals"](%s);out;' % BBOX
    body = urllib.parse.urlencode({"data": q}).encode()
    for url in SERVERS:
        try:
            req = urllib.request.Request(url, data=body, headers={"User-Agent": "osm-signals/1.0"})
            with urllib.request.urlopen(req, timeout=120) as r:
                text = r.read().decode("utf-8")
            if text.lstrip().startswith("{"):
                with open(RAW, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
                print("OK", url)
                return
            print("FAIL", url, text[:100])
        except Exception as ex:
            print("ERR", url, ex)
    sys.exit("no Overpass server answered")


def main():
    if "--offline" not in sys.argv:
        fetch()
    data = json.load(open(RAW, encoding="utf-8"))
    pts = []
    for e in data.get("elements", []):
        if e.get("type") == "node":
            x, z = xy(e["lat"], e["lon"])
            pts.append((round(x / STUD), round(z / STUD)))
    pts.sort()
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/osm_signals.py from OpenStreetMap data (c) OpenStreetMap contributors, ODbL.\n")
        f.write("-- Real traffic signals { x, z } in studs; shared/Traffic lights only junctions near one of these.\n")
        f.write("return {\n")
        for x, z in pts:
            f.write("\t{ %d, %d },\n" % (x, z))
        f.write("}\n")
    print("signals: %d -> %s" % (len(pts), os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
